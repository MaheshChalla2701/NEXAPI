"""Generate the SYNTHETIC dataset for the Q2 -> Q3 revenue-decline scenario.

    python3 -m datagen.generate            # writes data/, builds var/warehouse.sqlite, checks it

Steps: simulate customers -> calibrate the one calibrated lever so the revenue dashboard
shows -6.0% -> write raw files (deterministic bytes) -> integrity checks -> build the
scenario's warehouse and run its dashboards -> write data/MANIFEST.json and
data/ASSUMPTIONS.md. Fails loudly if any check does not hold.
"""

from __future__ import annotations

import argparse
import csv
import datetime as dt
import gzip
import hashlib
import io
import json
import shutil
import sys
import time
from collections import Counter
from pathlib import Path

import numpy as np
import pandas as pd

from datagen import events as E
from datagen import simulate as S
from datagen import tickets as T
from datagen.config import ASSUMPTIONS, COUNTRIES, P, fx_usd_per_unit

ROOT = Path(__file__).resolve().parent.parent
LABEL = "SYNTHETIC DATA - generated by datagen/ for an exercise. Not real company data."


class GenerationError(RuntimeError):
    pass


def iso(v) -> str:
    if v is None:
        return ""
    if isinstance(v, dt.datetime):
        return v.strftime("%Y-%m-%dT%H:%M:%SZ")
    if isinstance(v, dt.date):
        return v.isoformat()
    if isinstance(v, float):
        return f"{v:.2f}"
    return str(v)


def write_csv(path: Path, columns: list[str], rows: list[dict]) -> None:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(columns)
    for r in rows:
        w.writerow([iso(r.get(c)) for c in columns])
    path.write_text(buf.getvalue(), encoding="utf-8")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


# ------------------------------------------------------------------------------------------
# calibration

def calibrate(promo: list[tuple], base_q2: float, base_q3: float) -> tuple[float, float, list[str]]:
    """Choose the promo annual share so the dashboard change rounds to the brief's -6.0%.

    promo: (u_plan, annual_billing, monthly_billing) per promotion-window converter. A converter
    takes the annual plan iff u_plan < share, so sweeping the share over the sorted u values
    enumerates every achievable outcome exactly.
    """
    target = P["revenue_target_pct"]
    order = sorted(promo, key=lambda x: x[0])
    q2 = base_q2 + sum(m.q2_usd for _, _, m in order)
    q3 = base_q3 + sum(m.q3_usd for _, _, m in order)
    best = None
    for k in range(len(order) + 1):
        if k > 0:
            _, a, m = order[k - 1]
            q2 += a.q2_usd - m.q2_usd
            q3 += a.q3_usd - m.q3_usd
        change = 100 * (q3 / q2 - 1)
        if best is None or abs(change - target) < abs(best[1] - target):
            best = (k, change)
    k, change = best
    lo = order[k - 1][0] if k > 0 else 0.0
    hi = order[k][0] if k < len(order) else 1.0
    share = round((lo + hi) / 2, 6)
    notes = [f"promotion converters: {len(order)}", f"annual takers chosen: {k}"]
    if round(change, 1) != target:
        raise GenerationError(f"Calibration could not reach {target}% (closest {change:.3f}%).")
    if share < P["annual_share"]:
        raise GenerationError(f"Calibrated promo share {share:.3f} is below the normal annual share; "
                              "a promotion cannot lower it. Revisit the assumptions.")
    return share, change, notes


# ------------------------------------------------------------------------------------------
# main build

def generate(out: Path) -> dict:
    t0 = time.time()
    log = lambda m: print(f"[{time.time() - t0:6.1f}s] {m}", flush=True)  # noqa: E731

    partners = S.make_partners()
    workspaces = S.generate_workspaces(partners)
    log(f"{len(workspaces):,} workspaces")
    funnels = [S.funnel(w) for w in workspaces]

    billing: dict[int, S.Billing] = {}
    promo: list[tuple] = []
    promo_idx: list[int] = []
    for w, f in zip(workspaces, funnels):
        if w.origin != "initial" and S.in_promo(f):
            promo.append((f.u_plan, S.bill(w, f, "annual", 1), S.bill(w, f, "monthly", 2)))
            promo_idx.append(w.idx)
            continue
        interval = w.initial_interval if w.origin == "initial" else (
            "annual" if f.u_plan < P["annual_share"] else "monthly")
        billing[w.idx] = S.bill(w, f, interval, 0)
    base_q2 = sum(b.q2_usd for b in billing.values())
    base_q3 = sum(b.q3_usd for b in billing.values())
    share, change, notes = calibrate(promo, base_q2, base_q3)
    for idx, (u, a, m) in zip(promo_idx, promo):
        billing[idx] = a if u < share else m
    log(f"calibrated promo_annual_share = {share:.4f} -> dashboard revenue change {change:.3f}%")

    if out.exists():
        shutil.rmtree(out_tmp := out.with_name(out.name + ".old"), ignore_errors=True)
        readme = out / "README.md"
        keep = readme.read_bytes() if readme.exists() else None
        out.rename(out_tmp)
        out.mkdir()
        if keep is not None:
            readme.write_bytes(keep)
        shutil.rmtree(out_tmp)
    else:
        out.mkdir(parents=True)
    (out / "events").mkdir()

    owners_initial = {w.owner_hash for w in workspaces if w.origin == "initial"}

    # workspaces.parquet ------------------------------------------------------------------
    def current_plan(b: S.Billing | None) -> tuple[str, str]:
        if not b or not b.subscription:
            return "free", "free"
        s = b.subscription
        plan = f"{s['plan']}_{s['billing_interval']}"
        return plan, {"ended": "churned", "past_due": "past_due"}.get(s["status"], "paying")

    rows = []
    for w in sorted(workspaces, key=lambda x: (x.created_at, x.workspace_id)):
        plan, status = current_plan(billing.get(w.idx))
        rows.append({"workspace_id": w.workspace_id, "created_at": w.created_at, "country": w.country,
                     "company_size": w.size, "signup_channel": w.channel, "owner_email_hash": w.owner_hash,
                     "current_plan": plan, "current_status": status})
    wdf = pd.DataFrame(rows)
    wdf["created_at"] = pd.to_datetime(wdf["created_at"]).dt.tz_localize("UTC").astype("datetime64[us, UTC]")
    wdf.to_parquet(out / "workspaces.parquet", index=False, engine="pyarrow")

    # subscriptions.csv / payments.csv ------------------------------------------------------
    subs = sorted((b.subscription for b in billing.values() if b.subscription),
                  key=lambda s: (s["started_at"], s["subscription_id"]))
    sub_cols = ["subscription_id", "workspace_id", "plan", "billing_interval", "currency", "list_price",
                "discount_pct", "started_at", "cancelled_at", "ended_at", "cancel_reason", "status"]
    write_csv(out / "subscriptions.csv", sub_cols, subs)
    pays = sorted((p for b in billing.values() for p in b.payments if p["created_at"].date() >= S.SIM_START),
                  key=lambda p: (p["created_at"], p["payment_id"]))
    pay_cols = ["payment_id", "invoice_id", "subscription_id", "workspace_id", "type", "status", "attempt",
                "amount", "currency", "created_at", "period_start", "period_end", "failure_code", "refund_of"]
    write_csv(out / "payments.csv", pay_cols, pays)
    log(f"{len(subs):,} subscriptions, {len(pays):,} payment rows")

    # fx_rates.csv ---------------------------------------------------------------------------
    fx_rows = []
    for i in range(22):
        y, m = 2025 + i // 12, i % 12 + 1
        for cur in ("EUR", "GBP", "USD"):
            fx_rows.append({"month": f"{y}-{m:02d}", "currency": cur, "usd_per_unit": f"{fx_usd_per_unit(cur, y, m):.4f}"})
    write_csv(out / "fx_rates.csv", ["month", "currency", "usd_per_unit"], fx_rows)

    # experiment.csv ---------------------------------------------------------------------------
    rng = S.rng_for(7)
    exp = []
    for w in workspaces:
        if w.exp_arm is None or w.created_at.date() == P["dq_experiment_missing_day"]:
            continue
        row = {"experiment_id": "onboarding_v2_test", "workspace_id": w.workspace_id, "country": w.country,
               "variant": "new_onboarding" if w.exp_arm == "treatment" else "control",
               "assigned_at": w.created_at + dt.timedelta(seconds=int(rng.integers(1, 30)))}
        exp.append(row)
        if rng.random() < P["dq_experiment_duplicate_rows"]:
            exp.append({**row, "assigned_at": row["assigned_at"] + dt.timedelta(seconds=int(rng.integers(30, 600)))})
    exp.sort(key=lambda r: (r["assigned_at"], r["workspace_id"]))
    write_csv(out / "experiment.csv", ["experiment_id", "workspace_id", "country", "variant", "assigned_at"], exp)

    # referrals.csv -----------------------------------------------------------------------------
    pids = [p.partner_id for p in partners]
    pw = np.array([p.weight for p in partners])
    refs = []
    for w in workspaces:
        if not w.origin.startswith("referral"):
            continue
        refs.append({"partner_id": w.partner_id, "workspace_id": w.workspace_id,
                     "referred_at": w.created_at - dt.timedelta(seconds=int(rng.integers(60, 3600)))})
        if rng.random() < P["referral_duplicate_claims"]:
            other = pids[int(rng.choice(len(pids), p=pw))]
            if other != w.partner_id:
                refs.append({"partner_id": other, "workspace_id": w.workspace_id,
                             "referred_at": w.created_at + dt.timedelta(hours=int(rng.integers(1, 48)))})
    n_ref_ws = sum(1 for w in workspaces if w.origin.startswith("referral"))
    old = [w for w in workspaces if w.origin in ("initial", "organic") and w.created_at.date() < dt.date(2026, 7, 1)]
    span = (P["extract_date"] - P["referral_launch"]).days
    for _ in range(round(P["referral_preexisting_claims"] * n_ref_ws)):
        w = old[int(rng.integers(0, len(old)))]
        refs.append({"partner_id": pids[int(rng.choice(len(pids), p=pw))], "workspace_id": w.workspace_id,
                     "referred_at": S.at(P["referral_launch"] + dt.timedelta(days=int(rng.integers(0, span))), rng)})
    refs.sort(key=lambda r: (r["referred_at"], r["workspace_id"], r["partner_id"]))
    ref_rows = []
    for i, r in enumerate(refs, start=1):
        if rng.random() < 0.03:
            status, paid_at = "rejected", None
        elif r["referred_at"].date() < dt.date(2026, 9, 1):
            status, paid_at = "paid", dt.date(2026, 9, 15)
        else:
            status, paid_at = "pending", None
        ref_rows.append({"referral_id": f"rf_{i:06d}", "partner_id": r["partner_id"],
                         "referral_code": f"{r['partner_id'].upper().replace('_', '')}-LINK",
                         "referred_workspace_id": r["workspace_id"], "referred_at": r["referred_at"],
                         "payout_usd": P["referral_payout_usd"], "payout_status": status, "payout_paid_at": paid_at})
    write_csv(out / "referrals.csv", ["referral_id", "partner_id", "referral_code", "referred_workspace_id",
                                      "referred_at", "payout_usd", "payout_status", "payout_paid_at"], ref_rows)

    # support_tickets.csv -------------------------------------------------------------------------
    tk = []
    for w, f in zip(workspaces, funnels):
        b = billing.get(w.idx) or S.Billing()
        tk += T.tickets_for(w, f, b)
        if w.origin == "referral_incremental" and w.owner_hash in owners_initial:
            tk += T.duplicate_owner_tickets(w)
    tk.sort(key=lambda r: (r["created_at"], r["workspace_id"]))
    for i, r in enumerate(tk, start=1):
        r["ticket_id"] = f"tk_{i:06d}"
    write_csv(out / "support_tickets.csv", ["ticket_id", "workspace_id", "created_at", "channel", "subject", "body"], tk)
    log(f"{len(exp):,} experiment rows, {len(ref_rows):,} referral rows, {len(tk):,} tickets")

    # events/ ----------------------------------------------------------------------------------
    parts = [E.workspace_events(w, f, billing.get(w.idx) or S.Billing()) for w, f in zip(workspaces, funnels)]
    parts = [p for p in parts if p is not None]
    ev = {k: np.concatenate([p[k] for p in parts]) for k in parts[0]}
    order = np.lexsort((ev["type"], ev["ws"], ev["ts"]))
    ev = {k: v[order] for k, v in ev.items()}
    n_total = len(ev["ts"])
    erng = S.rng_for(8)
    file_day = ev["ts"] // 86400
    late = erng.random(n_total) < P["dq_late_event_share"]
    file_day = file_day + late
    missing = (dt.datetime.combine(P["dq_missing_event_day"], dt.time()) - E.EPOCH).days
    extract_day = (dt.datetime.combine(P["extract_date"], dt.time()) - E.EPOCH).days
    keep = (file_day != missing) & (file_day < extract_day)
    ids = np.arange(1, n_total + 1)
    ws_ids = [w.workspace_id for w in workspaces]
    by_day = np.argsort(file_day[keep], kind="stable")
    sel = np.nonzero(keep)[0][by_day]
    days_sorted = file_day[sel]
    bounds = np.flatnonzero(np.diff(days_sorted)) + 1
    n_written = 0
    for chunk in np.split(sel, bounds):
        if chunk.size == 0:
            continue
        day = (E.EPOCH + dt.timedelta(days=int(file_day[chunk[0]]))).date()
        lines = ["event_id,workspace_id,user_id,event_type,event_ts,properties"]
        for i in chunk:
            wid = ws_ids[ev["ws"][i]]
            typ = E.EVENT_TYPES[ev["type"][i]]
            flow = ev["flow"][i]
            if typ == "onboarding_step_completed":
                props = f"flow=v{flow};step={ev['step'][i]}"
            elif typ == "onboarding_email_clicked":
                props = f"flow=v2;email={ev['step'][i]}"
            elif typ == "workspace_created":
                props = f"flow=v{flow}"
            else:
                props = ""
            when = (E.EPOCH + dt.timedelta(seconds=int(ev["ts"][i]))).strftime("%Y-%m-%dT%H:%M:%SZ")
            lines.append(f"ev_{ids[i]:09d},{wid},{wid}-u{ev['user'][i]},{typ},{when},{props}")
        with open(out / "events" / f"{day.isoformat()}.csv.gz", "wb") as fh:
            with gzip.GzipFile(filename="", mode="wb", fileobj=fh, mtime=0) as gz:
                gz.write(("\n".join(lines) + "\n").encode("utf-8"))
        n_written += chunk.size
    log(f"{n_written:,} events written ({n_total - n_written:,} lost to the missing day / extract cut-off)")

    checks = integrity_checks(out, workspaces, subs, pays, exp, ref_rows, tk)
    log(f"{len(checks)} integrity checks passed")

    # scenario warehouse + dashboards -----------------------------------------------------------
    from scripts import build_warehouse, run_dashboards

    wh = ROOT / "var" / "warehouse.sqlite"
    build_warehouse.build(out, wh)
    dash = run_dashboards.run(wh)
    q3 = next(r for r in dash["revenue"] if r["quarter"] == "2026-Q3")
    if q3["change_vs_prev_quarter_pct"] != P["revenue_target_pct"]:
        raise GenerationError(f"Revenue dashboard shows {q3['change_vs_prev_quarter_pct']}%, expected "
                              f"{P['revenue_target_pct']}%")
    checks.append(f"revenue dashboard (SQL) reproduces {q3['change_vs_prev_quarter_pct']}% Q3 vs Q2")
    log("dashboards run; revenue dashboard shows the brief's -6.0%")

    files = sorted(p for p in out.rglob("*") if p.is_file() and p.name not in ("README.md",))
    manifest = {
        "label": LABEL,
        "seed": P["seed"],
        "generator": "datagen (see datagen/config.py for every assumption)",
        "calibration": {"parameter": "promo_annual_share", "value": share,
                        "dashboard_revenue_change_pct_unrounded": round(change, 4), "notes": notes},
        "row_counts": {
            "workspaces": len(rows), "subscriptions": len(subs), "payments": len(pays), "experiment": len(exp),
            "referrals": len(ref_rows), "support_tickets": len(tk), "events": n_written,
            "event_files": len(list((out / "events").glob("*.csv.gz"))), "fx_rates": len(fx_rows)},
        "scenario_dashboards": dash,
        "integrity_checks": checks,
        "files": {str(p.relative_to(out)): sha256(p) for p in files if p.name != "MANIFEST.json"},
    }
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=2, default=str) + "\n")
    write_assumptions_md(out / "ASSUMPTIONS.md", share, change)
    log(f"done: {out}")
    return manifest


def integrity_checks(out, workspaces, subs, pays, exp, refs, tk) -> list[str]:
    ok: list[str] = []

    def check(cond: bool, msg: str) -> None:
        if not cond:
            raise GenerationError(f"Integrity check failed: {msg}")
        ok.append(msg)

    ws_ids = {w.workspace_id for w in workspaces}
    created = {w.workspace_id: w.created_at for w in workspaces}
    check(len(ws_ids) == len(workspaces), "workspace_id unique")
    sub_ids = {s["subscription_id"] for s in subs}
    check(len(sub_ids) == len(subs), "subscription_id unique")
    check(all(s["workspace_id"] in ws_ids for s in subs), "every subscription belongs to a workspace")
    check(all(s["started_at"] >= created[s["workspace_id"]] for s in subs), "subscriptions start after workspace creation")
    check(all(p["subscription_id"] in sub_ids for p in pays), "every payment belongs to a subscription")
    starts = {s["subscription_id"]: s["started_at"].date() for s in subs}
    check(all(p["period_start"] >= starts[p["subscription_id"]] for p in pays), "billing periods start on/after subscription start")
    counts = Counter(p["payment_id"] for p in pays)
    dups = sum(c - 1 for c in counts.values() if c > 1)
    check(dups > 0, f"planted duplicate payment rows present ({dups})")
    exp_ws = Counter(r["workspace_id"] for r in exp)
    check(all(w in ws_ids for w in exp_ws), "experiment rows reference existing workspaces")
    country = {w.workspace_id: w.country for w in workspaces}
    check(all(country[r["workspace_id"]] == r["country"] for r in exp), "experiment country matches workspace country")
    check(all(r["referred_workspace_id"] in ws_ids for r in refs), "referrals reference existing workspaces")
    check(all(t["workspace_id"] in ws_ids for t in tk), "tickets reference existing workspaces")
    ev_ws, ev_bad = 0, 0
    for path in sorted((out / "events").glob("*.csv.gz")):
        for chunk in pd.read_csv(path, usecols=["workspace_id", "event_ts"], chunksize=500_000):
            ev_ws += (~chunk["workspace_id"].isin(ws_ids)).sum()
            c = pd.to_datetime(chunk["workspace_id"].map(created))
            ev_bad += (pd.to_datetime(chunk["event_ts"]).dt.tz_localize(None) < c).sum()
    check(ev_ws == 0, "events reference existing workspaces")
    check(ev_bad == 0, "no event precedes its workspace's creation")
    check(not (out / "events" / f"{P['dq_missing_event_day'].isoformat()}.csv.gz").exists(), "planted missing event day absent")
    return ok


def write_assumptions_md(path: Path, share: float, change: float) -> None:
    kinds = {"brief": "From the brief", "assumption": "Our assumption", "scenario": "Scenario design (cause or data problem)",
             "calibrated": "Calibrated", "scale": "Scale limit"}
    lines = [f"# Synthetic dataset assumptions\n\n> **{LABEL}**\n",
             "Generated from `datagen/config.py`, so this file always matches the code. "
             "Regenerate with `python3 -m datagen.generate`.\n",
             f"Calibrated: `promo_annual_share` = **{share:.4f}**, giving a revenue-dashboard change of "
             f"{change:.3f}% (displayed as {round(change, 1)}%).\n",
             "| Kind | Key | Value | Meaning |", "|---|---|---|---|"]
    for a in ASSUMPTIONS:
        val = share if a.key == "promo_annual_share" else a.value
        txt = json.dumps(val, default=str) if not isinstance(val, str) else val
        lines.append(f"| {kinds[a.kind]} | `{a.key}` | `{txt}` | {a.description} |")
    lines += ["", "## Countries", "", "| Country | Share of sign-ups | Billing currency | Europe |", "|---|---|---|---|"]
    lines += [f"| {c} | {w:.0%} | {cur} | {'yes' if eu else 'no'} |" for c, w, cur, eu in COUNTRIES]
    path.write_text("\n".join(lines) + "\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT / "data")
    args = ap.parse_args(argv)
    try:
        generate(args.out)
    except GenerationError as exc:
        print(f"GENERATION FAILED: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
